#!/usr/bin/env bash
# Development stage 2 — run ONLY on a fresh Debian 13 test VM.
set -Eeuo pipefail
umask 077
fail() { printf 'FEHLER: %s\n' "$*" >&2; exit 1; }
[[ "$(id -u)" -ne 0 ]] || fail "Als sudo-Benutzer ausführen, nicht als root."
sudo -v || fail "sudo fehlt."
# shellcheck disable=SC1091
source /etc/os-release
[[ "${ID:-}" == debian && "${VERSION_ID:-}" == 13 ]] || fail "Nur Debian 13."
[[ "$(uname -m)" == x86_64 ]] || fail "BCHN-Archiv ist nur für x86_64."
CONF="$HOME/.config/bch-solo-installer/setup.env"
[[ -f "$CONF" && ! -L "$CONF" ]] || fail "Zuerst bash install.sh ausführen."
[[ "$(stat -c %a "$CONF")" == 600 ]] || fail "setup.env muss Modus 600 haben."
# Values in setup.env were generated by stage 1; never source arbitrary downloaded files.
# shellcheck disable=SC1090
source "$CONF"
[[ "${RPC_USER:-}" == bchpool && "${RPC_PASSWORD:-}" =~ ^[0-9a-f]{64}$ ]] || fail "RPC-Konfiguration ungültig."
[[ "${BCH_ADDRESS:-}" =~ ^1[123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz]{25,34}$ ]] || fail "BCH-Adresse fehlt."
for p in /var/lib/bch-node /usr/local/bin/bitcoind /usr/local/bin/bitcoin-cli /etc/systemd/system/bchn.service /opt/bch-solo-pool; do
  [[ ! -e "$p" ]] || fail "Bestehender Pfad: $p — nichts überschreiben."
done
id bchn &>/dev/null && fail "Systembenutzer bchn existiert bereits."
# Choose and validate backup before downloading/installing BCHN.
printf '\033[1;32m%s\033[0m' 'Ist ein Blockchain-Backup vorhanden? [j/N] '
read -r USE_BACKUP
BACKUP_ARCHIVE=""
if [[ "$USE_BACKUP" =~ ^[jJyY]$ ]]; then
  printf '\033[1;32m%s\033[0m' 'Pfad zum Backup: Beispiel [/var/backups/bchn/bchn-blockchain.tar.gz]: '
  read -r BACKUP_ARCHIVE
  BACKUP_ARCHIVE="${BACKUP_ARCHIVE:-/var/backups/bchn/bchn-blockchain.tar.gz}"
  [[ -f "$BACKUP_ARCHIVE" && -r "$BACKUP_ARCHIVE" ]] || fail "Backup nicht lesbar: $BACKUP_ARCHIVE"
  gzip -t "$BACKUP_ARCHIVE" || fail "Backup beschädigt oder unvollständig."
  python3 - "$BACKUP_ARCHIVE" <<'PY' || fail "Archivstruktur ungültig."
import sys, tarfile
seen=set()
with tarfile.open(sys.argv[1], "r:gz") as t:
    for m in t:
        n=m.name.removeprefix("./").rstrip("/")
        if n in ("bch-node/blocks", "bch-node/chainstate"):
            seen.add(n)
        if n not in ("bch-node", "bch-node/blocks", "bch-node/chainstate") and not n.startswith(("bch-node/blocks/", "bch-node/chainstate/")):
            raise SystemExit("Unerwarteter Archiveintrag: "+n)
        if ".." in n.split("/") or m.issym() or m.islnk() or not (m.isfile() or m.isdir()):
            raise SystemExit("Unsicherer Archiveintrag: "+n)
if seen != {"bch-node/blocks", "bch-node/chainstate"}:
    raise SystemExit("Verzeichnisse blocks/chainstate fehlen.")
PY
  echo "Backup geprüft: $BACKUP_ARCHIVE"
else
  echo "Kein Backup gewählt: Blockchain wird neu synchronisiert."
fi
echo "BCHN 29.2.0 wird automatisch heruntergeladen und installiert ..."
sudo apt-get update
sudo apt-get install -y curl wget git ca-certificates gnupg tar gzip jq \
  build-essential yasm autoconf automake libtool pkgconf \
  libzmq3-dev libsodium-dev libcurl4-openssl-dev libjansson-dev libssl-dev \
  python3 python3-venv python3-pip openssl
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
ARCHIVE="bitcoin-cash-node-29.2.0-x86_64-linux-gnu.tar.gz"
wget --https-only -O "$TMP/$ARCHIVE" "https://github.com/bitcoin-cash-node/bitcoin-cash-node/releases/download/v29.2.0/$ARCHIVE"
echo "23bbe9ff749136a9b832a2a59023ce76a5391322c1ea2f4f24b5b91f035081bc  $TMP/$ARCHIVE" | sha256sum -c - || fail "SHA256 stimmt nicht!"
echo "HINWEIS: SHA256 stammt aus der Referenzinstallation; Signaturprüfung des Herausgebers steht noch aus."
tar -xzf "$TMP/$ARCHIVE" -C "$TMP"
[[ -f "$TMP/bitcoin-cash-node-29.2.0/bin/bitcoind" && -f "$TMP/bitcoin-cash-node-29.2.0/bin/bitcoin-cli" ]] || fail "Archivstruktur unerwartet."
sudo useradd --system --user-group --home-dir /var/lib/bch-node --shell /usr/sbin/nologin bchn

sudo install -d -o bchn -g bchn -m 750 /var/lib/bch-node
sudo install -d -o "$(id -un)" -g "$(id -gn)" -m 750 /opt/bch-solo-pool
sudo usermod -aG bchn "$(id -un)"
sudo install -m 755 "$TMP/bitcoin-cash-node-29.2.0/bin/bitcoind" /usr/local/bin/bitcoind
sudo install -m 755 "$TMP/bitcoin-cash-node-29.2.0/bin/bitcoin-cli" /usr/local/bin/bitcoin-cli
# Write root-owned staging files, then install with explicit ownership and permissions.
cat >"$TMP/bitcoin.conf" <<EOF
server=1
daemon=0
prune=550
txindex=0
dbcache=2048
listen=1
port=8333
maxconnections=32
rpcbind=127.0.0.1
rpcallowip=127.0.0.1
rpcport=8332
blocksonly=0
rpcuser=$RPC_USER
rpcpassword=$RPC_PASSWORD
EOF
sudo install -o bchn -g bchn -m 640 "$TMP/bitcoin.conf" /var/lib/bch-node/bitcoin.conf
cat >"$TMP/bchn.service" <<'EOF'
[Unit]
Description=Bitcoin Cash Node (Mainnet)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=bchn
Group=bchn
WorkingDirectory=/var/lib/bch-node
ExecStart=/usr/local/bin/bitcoind -datadir=/var/lib/bch-node -conf=/var/lib/bch-node/bitcoin.conf
ExecStop=/usr/local/bin/bitcoin-cli -datadir=/var/lib/bch-node -conf=/var/lib/bch-node/bitcoin.conf stop
Restart=on-failure
RestartSec=10
TimeoutStopSec=300
LimitNOFILE=65536

[Install]
WantedBy=multi-user.target
EOF
sudo install -o root -g root -m 644 "$TMP/bchn.service" /etc/systemd/system/bchn.service
sudo systemctl daemon-reload
echo "BCHN installiert."
if [[ -n "$BACKUP_ARCHIVE" ]]; then
  BCHN_AUTO_RESTORE=1 bash "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/09-restore-blockchain.sh" "$BACKUP_ARCHIVE"
  sudo test -d /var/lib/bch-node/blocks && sudo test -d /var/lib/bch-node/chainstate || fail "Backup nicht wiederhergestellt. BCHN wird nicht gestartet."
fi
echo "Starte BCHN und beginne Blockchain-Synchronisierung ..."
sudo systemctl enable --now bchn.service
sudo systemctl is-active --quiet bchn.service || fail "BCHN konnte nicht gestartet werden."
echo "BCHN gestartet. Installer wartet anschließend auf die vollständige Synchronisierung."
